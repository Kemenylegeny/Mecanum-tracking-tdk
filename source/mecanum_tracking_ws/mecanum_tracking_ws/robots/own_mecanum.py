"""Configuration of our own (real) mecanum robot (``robot_name = "own"``).

Originally copied from ``mecanum_ws/source/mecanum_ws/mecanum_ws/robots/own_mecanum.py`` (the URDF path pointing
into this project). In mecanum_ws the geometry was measured from the CAD STL (``assets/robots/own_mecanum/stl``,
``scripts/tools/analyze_wheel_mesh.py``) and the URDF generated by
``scripts/tools/generate_mecanum_robot.py --config assets/robots/own_mecanum/robot_config.json``:
rigid chassis (the Fusion 360 ``MecanumRobot_orientalt_v2`` base_link), four 60.6 mm wheels with 9 rubber-coated 45 deg
rollers each (6 collision spheres per roller), 41 links.

Same constant names as :mod:`mecanum_tracking_ws.robots.mecanum`, so the task can switch robots (``robot_name``).

Since 2026-10-23 (RL vs. LTV-MPC alignment, docs/OSSZEHANGOLAS.md 3.1, 3.3) this is the SAME plant as the MPC's:
* URDF ``robot_measured.urdf``: the MPC side's ``tb3_sim_bringup/models/own_mecanum/robot.urdf`` (Mecanum-Robot-MPC-TDK
  @ fe01f88) with the WEIGHED masses (body 1927.4 g, wheel 51.65 g; m = 2.134 kg). Apart from the ``<inertial>`` tags
  it is identical to ``robot.urdf`` (checked with diff), and the MPC reads its model from the same file
  (``mpc.params.from_urdf``: m_e = 2.215 kg, J_e = 0.03035 kg m^2).
* Motor: DYNAMIXEL XM430-W210-T at 12 V (= ``mpc/motor.py``), driven in torque (current) mode: no velocity loop, no
  armature. :data:`MECANUM_CFG` (torque, the comparison) vs. :data:`MECANUM_VEL_CFG` (velocity loop, only for the
  twist / wheel-speed action ablation).
The rubber contact values are still guesses (the same for both controllers, as they share the env).
"""

from pathlib import Path

import isaaclab.sim as sim_utils
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets import ArticulationCfg

from .actuators import XM430MotorCfg

PROJECT_ROOT = Path(__file__).resolve().parents[4]
URDF_PATH = PROJECT_ROOT / "assets" / "robots" / "own_mecanum" / "robot_measured.urdf"
"""Weighed masses (2.134 kg); the MPC builds its model from the same file."""
URDF_PATH_GUESSED = PROJECT_ROOT / "assets" / "robots" / "own_mecanum" / "robot.urdf"
"""The original URDF with the guessed masses (3.0 kg), kept for reference."""

BASE_LINK_NAME = "base_link"
WHEEL_JOINT_NAMES = [
    "front_left_wheel_joint",
    "front_right_wheel_joint",
    "rear_left_wheel_joint",
    "rear_right_wheel_joint",
]
ROLLER_JOINT_NAMES = [".*_roller_.*_joint"]
WHEEL_JOINT_SIGNS = (1.0, 1.0, 1.0, 1.0)

# geometry (must match the URDF / robot_config.json)
WHEEL_RADIUS = 0.03028
"""Roller envelope radius [m] (CAD: 60.6 mm diameter)."""
WHEEL_BASE_HALF_LENGTH = 0.064
"""lx [m]."""
TRACK_HALF_WIDTH = 0.1526
"""ly [m]."""
WHEEL_Z = -0.0415
"""Wheel axle height w.r.t. the chassis center [m]."""
FOOTPRINT_HALF_EXTENTS = (0.133, 0.17)
"""Half length / width of the rectangle enclosing the robot incl. wheels [m] (assembly STL: 265.5 x 338.9 mm)."""

# motor: DYNAMIXEL XM430-W210-T at 12.0 V, one per wheel (ROBOTIS e-manual; the same numbers as mpc/motor.py)
MOTOR_NO_LOAD_SPEED = 8.06
"""No-load speed [rad/s] (77 rpm; = the MPC's omega_max). ~0.24 m/s at the wheel rim."""
MOTOR_STALL_TORQUE = 3.0
"""Stall torque [Nm] (locked rotor): sets the slope of the linear torque-speed curve of the DC motor model."""
WHEEL_EFFORT_LIMIT = 1.95
"""Torque limit [Nm]: the maximum of the 12 V performance graph (= the MPC's u_max). With the linear curve the motor
gives the full 1.95 Nm only below 2.8 rad/s, above that 3.0 * (1 - w / 8.06)."""
MAX_WHEEL_SPEED = MOTOR_NO_LOAD_SPEED
"""Wheel speed scale of the observations and of the velocity-loop ablation [rad/s]."""
WHEEL_DAMPING = 0.1
"""Velocity-loop gain [Nm*s/rad] of :data:`MECANUM_VEL_CFG` only (the torque config has none)."""
WHEEL_ARMATURE = 9.0e-4
"""Armature [kg*m^2] of :data:`MECANUM_VEL_CFG` only: the explicit velocity loop needs it for stability
(d*dt/(I + armature) = 0.3). The torque config has 0 (no rotor inertia data; system identification later)."""
ROLLER_DAMPING = 1.0e-5
AXLE_JOINT_NAMES: list[str] = []
"""Rigid chassis: no pendulum axle."""

SPAWN_HEIGHT = WHEEL_RADIUS - WHEEL_Z + 0.001
"""Initial height of the base link [m] (1 mm above the ground contact; was 5 mm until 2026-10-23: the robot then
falls for ~30 ms after every reset, and a controller's torques spin the free wheels up meanwhile)."""

# rubber-coated rollers: ~0.3 mm deflection under a quarter of the (guessed) 3 kg weight (7.4 N); ~0.2 mm with the
# weighed 2.134 kg
ROLLER_CONTACT_STIFFNESS = 2.5e4
"""[N/m]; only effective on the ground material."""
ROLLER_CONTACT_DAMPING = 110.0
"""[N*s/m] (damping ratio ~0.4 with ~0.75 kg per wheel)."""
ROLLER_FRICTION = 0.9
"""Rubber on a hard floor (GUESS); the navigation task randomizes 0.5-1.1."""

ROBOT_MATERIAL = sim_utils.RigidBodyMaterialCfg(
    static_friction=ROLLER_FRICTION,
    dynamic_friction=ROLLER_FRICTION,
    friction_combine_mode="multiply",
    restitution_combine_mode="multiply",
    compliant_contact_stiffness=ROLLER_CONTACT_STIFFNESS,
    compliant_contact_damping=ROLLER_CONTACT_DAMPING,
)
"""Material of the robot colliders (set as the default material of the simulation, the URDF binds none)."""


def ground_material(friction: float = 1.0) -> sim_utils.RigidBodyMaterialCfg:
    """Ground material carrying the roller contact compliance (multiply-combined with the roller friction)."""
    return sim_utils.RigidBodyMaterialCfg(
        static_friction=friction,
        dynamic_friction=friction,
        friction_combine_mode="multiply",
        restitution_combine_mode="multiply",
        compliant_contact_stiffness=ROLLER_CONTACT_STIFFNESS,
        compliant_contact_damping=ROLLER_CONTACT_DAMPING,
    )


MECANUM_CFG = ArticulationCfg(
    spawn=sim_utils.UrdfFileCfg(
        asset_path=str(URDF_PATH),
        fix_base=False,
        merge_fixed_joints=True,
        make_instanceable=True,
        joint_drive=sim_utils.UrdfConverterCfg.JointDriveCfg(
            target_type="velocity",
            gains=sim_utils.UrdfConverterCfg.JointDriveCfg.PDGainsCfg(stiffness=0.0, damping=0.0),
        ),
        activate_contact_sensors=False,
        rigid_props=sim_utils.RigidBodyPropertiesCfg(disable_gravity=False, max_depenetration_velocity=1.0),
        articulation_props=sim_utils.ArticulationRootPropertiesCfg(
            enabled_self_collisions=False, solver_position_iteration_count=8, solver_velocity_iteration_count=1
        ),
    ),
    init_state=ArticulationCfg.InitialStateCfg(pos=(0.0, 0.0, SPAWN_HEIGHT), joint_pos={".*": 0.0}, joint_vel={".*": 0.0}),
    soft_joint_pos_limit_factor=1.0,
    actuators={
        # pure torque command (JointEffortAction): computed effort = the command, limited by the linear XM430
        # torque-speed curve, |tau| <= 3.0 (1 - |w|/8.06) toward the motion and |tau| <= 1.95, never reversed
        # (actuators.py: isaaclab's DCMotor would brake with up to 1.95 Nm above 8.06 rad/s, explicitly unstable with
        # these light wheels). The plant of BOTH controllers.
        "wheels": XM430MotorCfg(
            joint_names_expr=WHEEL_JOINT_NAMES,
            stiffness=0.0,
            damping=0.0,
            saturation_effort=MOTOR_STALL_TORQUE,
            effort_limit=WHEEL_EFFORT_LIMIT,
            velocity_limit=MOTOR_NO_LOAD_SPEED,
            armature=0.0,
        ),
        "rollers": ImplicitActuatorCfg(joint_names_expr=ROLLER_JOINT_NAMES, stiffness=0.0, damping=ROLLER_DAMPING),
    },
)
"""Our own mecanum robot with the weighed masses and torque-driven XM430 wheels (the comparison plant)."""

MECANUM_VEL_CFG = MECANUM_CFG.replace(
    actuators={
        "wheels": MECANUM_CFG.actuators["wheels"].replace(damping=WHEEL_DAMPING, armature=WHEEL_ARMATURE),
        "rollers": MECANUM_CFG.actuators["rollers"],
    }
)
"""The same robot with a wheel velocity loop (twist / wheel-speed setpoint actions): only for the action-space
ablation. NOTE: the armature it needs makes it a slightly different plant."""
